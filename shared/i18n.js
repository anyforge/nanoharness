let LANG = 'en';

async function loadLang() {
  try {
    const { nh_lang } = await chrome.storage.local.get('nh_lang');
    LANG = nh_lang === 'zh' ? 'zh' : 'en';
  } catch (e) { LANG = 'en'; }
}

function t(key) {
  return (I18N[LANG] && I18N[LANG][key]) ?? I18N.zh[key] ?? key;
}

function applyI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}

async function setLang(lang) {
  LANG = lang === 'zh' ? 'zh' : 'en';
  try { await chrome.storage.local.set({ nh_lang: LANG }); } catch (e) {}
  applyI18n();
  document.querySelectorAll('[data-lang-toggle]').forEach((el) => {
    el.classList.toggle('active', el.dataset.langToggle === LANG);
  });
}

function bindLangToggles() {
  document.querySelectorAll('[data-lang-toggle]').forEach((el) => {
    el.onclick = () => setLang(el.dataset.langToggle);
  });
}

// ---- 主题（明亮 / 暗色） ----
async function loadTheme() {
  try {
    const { nh_theme } = await chrome.storage.local.get('nh_theme');
    applyTheme(nh_theme === 'dark' ? 'dark' : 'light');
  } catch (e) { applyTheme('light'); }
}
function applyTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme === 'dark' ? 'dark' : 'light');
}
async function setTheme(theme) {
  applyTheme(theme);
  try { await chrome.storage.local.set({ nh_theme: theme === 'dark' ? 'dark' : 'light' }); } catch (e) {}
}
